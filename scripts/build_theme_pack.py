def encode_optimized_backdrop(src_path: str, max_width: int = 1280) -> tuple[str, int, str]:
    """Comprime y redimensiona una ilustración a WebP (o JPEG fallback) y devuelve (data_uri, bytes, mime)."""
    convert_bin = shutil.which("convert") or shutil.which("magick")
    ffmpeg_bin = shutil.which("ffmpeg")

    with tempfile.TemporaryDirectory(prefix="rcpack_img_") as tmpdir:
        webp_out = os.path.join(tmpdir, "out.webp")
        jpg_out = os.path.join(tmpdir, "out.jpg")

        # 1. Preferir WebP con ImageMagick o ffmpeg para tamaño mínimo y gran nitidez
        if convert_bin:
            res = subprocess.run(
                [
                    convert_bin,
                    src_path,
                    "-resize",
                    f"{max_width}x>",
                    "-strip",
                    "-quality",
                    "78",
                    webp_out,
                ],
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                check=False,
            )
            if res.returncode == 0 and os.path.isfile(webp_out) and os.path.getsize(webp_out) > 4096:
                raw = open(webp_out, "rb").read()
                b64 = base64.b64encode(raw).decode("ascii")
                return f"data:image/webp;base64,{b64}", len(raw), "image/webp"

        if ffmpeg_bin:
            res = subprocess.run(
                [
                    ffmpeg_bin,
                    "-y",
                    "-i",
                    src_path,
                    "-vf",
                    f"scale='min({max_width},iw)':-2",
                    "-c:v",
                    "libwebp",
                    "-quality",
                    "76",
                    webp_out,
                ],
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                check=False,
            )
            if res.returncode == 0 and os.path.isfile(webp_out) and os.path.getsize(webp_out) > 4096:
                raw = open(webp_out, "rb").read()
                b64 = base64.b64encode(raw).decode("ascii")
                return f"data:image/webp;base64,{b64}", len(raw), "image/webp"

        # 2. Fallback JPEG optimizado
        if convert_bin:
            res = subprocess.run(
                [
                    convert_bin,
                    src_path,
                    "-resize",
                    f"{max_width}x>",
                    "-strip",
                    "-interlace",
                    "Plane",
                    "-quality",
                    "76",
                    jpg_out,
                ],
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                check=False,
            )
            if res.returncode == 0 and os.path.isfile(jpg_out) and os.path.getsize(jpg_out) > 4096:
                raw = open(jpg_out, "rb").read()
                b64 = base64.b64encode(raw).decode("ascii")
                return f"data:image/jpeg;base64,{b64}", len(raw), "image/jpeg"

        # 3. Último recurso: archivo original directo
        raw = open(src_path, "rb").read()
        b64 = base64.b64encode(raw).decode("ascii")
        return f"data:image/jpeg;base64,{b64}", len(raw), "image/jpeg"


def collect_assets() -> dict[str, str]:
    assets: dict[str, str] = {}
    for asset_id, pattern in ASSET_GLOBS.items():
        matches = sorted(glob.glob(os.path.join(IMAGES_DIR, pattern)))
        if not matches:
            raise FileNotFoundError(f"Falta ilustración fuente para {asset_id} ({pattern}) en {IMAGES_DIR}")
        src = matches[-1]
        data_uri, size_bytes, mime = encode_optimized_backdrop(src)
        assets[asset_id] = data_uri
        print(f"  [asset] {asset_id:20s} <- {os.path.basename(src)} ({size_bytes // 1024} KB, {mime})")
    return assets


