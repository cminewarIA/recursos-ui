def main() -> None:
    os.makedirs(THEMES_DIR, exist_ok=True)
    print("Compilando paquete único de temas OTA (themes-pack.rcpack.gz)...")
    assets = collect_assets()
    themes = build_theme_definitions()

    body = {
        "schema_version": 2,
        "pack_version": PACK_VERSION,
        "default_theme": "alethia-matrix",
        "generated_at": int(time.time()),
        "assets": assets,
        "themes": themes,
    }

    canonical_json = json.dumps(body, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    pack_sha256 = hashlib.sha256(canonical_json).hexdigest()
    body["pack_sha256"] = pack_sha256
    final_json = json.dumps(body, ensure_ascii=False, separators=(",", ":")).encode("utf-8")

    pack_path = os.path.join(THEMES_DIR, PACK_FILENAME)
    tmp_pack = f"{pack_path}.tmp"
    with gzip.open(tmp_pack, "wb", compresslevel=9) as gz:
        gz.write(final_json)
    os.replace(tmp_pack, pack_path)

    gz_size = os.path.getsize(pack_path)
    print(f"OK -> {pack_path} ({gz_size // 1024} KB gzip, {len(final_json) // 1024} KB JSON, {len(themes)} temas, {len(assets)} fondos)")
    print(f"SHA-256: {pack_sha256}")

    # Actualizar alethia-matrix.json local (usado como fallback de arranque en el bundle Vite)
    matrix_theme = themes[0]
    matrix_path = os.path.join(THEMES_DIR, "alethia-matrix.json")
    with open(f"{matrix_path}.tmp", "w", encoding="utf-8") as fp:
        json.dump(matrix_theme, fp, ensure_ascii=False, indent=2)
        fp.write("\n")
    os.replace(f"{matrix_path}.tmp", matrix_path)

    # Actualizar manifiesto ligero themes.json apuntando al paquete único
    manifest = {
        "schema_version": 2,
        "pack_version": PACK_VERSION,
        "pack_file": PACK_FILENAME,
        "pack_sha256": pack_sha256,
        "default_theme": "alethia-matrix",
        "themes": [
            {
                "id": t["id"],
                "version": t["version"],
                "colorModePolicy": t.get("colorModePolicy", "dual"),
                "layout": t.get("layout", {}),
                "name": t["name"],
                "description": t["description"],
                "tags": t.get("tags", []),
                "has_animation": (t.get("backgroundEffect") or {}).get("type", "none") != "none",
                "file": "alethia-matrix.json" if t["id"] == "alethia-matrix" else "",
            }
            for t in themes
        ],
    }
    manifest_path = os.path.join(THEMES_DIR, "themes.json")
    with open(f"{manifest_path}.tmp", "w", encoding="utf-8") as fp:
        json.dump(manifest, fp, ensure_ascii=False, indent=2)
        fp.write("\n")
    os.replace(f"{manifest_path}.tmp", manifest_path)
    print("OK -> themes/alethia-matrix.json y themes/themes.json actualizados.")


if __name__ == "__main__":
    main()
